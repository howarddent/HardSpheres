"""Turn an OpenCL kernel file into a Pascal include holding it as a string
constant, so a program can carry its kernels inside the executable.

    python3 cl2inc.py <in.cl> <out.inc> <ConstName>
    python3 cl2inc.py --check <in.cl> <out.inc> <ConstName>

--check writes nothing and exits 1 if <out.inc> is not what <in.cl> would
give now, so a release script can refuse to build from a stale include.

FPC 3.2 has no portable way to embed a file at build time ({$R x.rc} needs
the MinGW windres on Linux and macOS, and -FF to use fpcres instead only
arrived in FPC 3.3), hence a generated, committed include. Each source line
becomes one string literal ending in #10; quotes are doubled, and any other
control character is written as #nn. Long lines are split, to keep every
literal well clear of compiler limits.
"""
import sys

CHUNK = 200


def literal(s):
    """Pascal expression for s: quoted runs, with #nn for control chars."""
    out, run = [], []
    for ch in s:
        if ord(ch) < 32 or ord(ch) == 127:
            if run:
                out.append("'" + "".join(run) + "'")
                run = []
            out.append("#%d" % ord(ch))
        else:
            run.append("''" if ch == "'" else ch)
    if run:
        out.append("'" + "".join(run) + "'")
    return "".join(out) if out else "''"


def generate(src_path, src, const_name):
    lines = src.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()          # the file's final newline; every line gets #10
    parts = []
    for ln in lines:
        pieces = [ln[i:i + CHUNK] for i in range(0, len(ln), CHUNK)] or [""]
        for p in pieces[:-1]:
            parts.append(literal(p))
        parts.append(literal(pieces[-1]) + "#10")
    name = src_path.replace("\\", "/").rsplit("/", 1)[-1]
    out = [
        "// Generated by tools/cl2inc.py from %s - do not edit." % name,
        "// Edit %s and regenerate this file; see cl2inc.py." % name,
        "const",
        "  %s =" % const_name,
    ]
    for i, p in enumerate(parts):
        out.append("    " + p + (" +" if i < len(parts) - 1 else ";"))
    if not parts:
        out.append("    '';")
    return "\n".join(out) + "\n"


def main(argv):
    check = argv[:1] == ["--check"]
    if check:
        argv = argv[1:]
    if len(argv) != 3:
        sys.exit(__doc__)
    src_path, inc_path, const_name = argv
    with open(src_path, encoding="utf-8", newline="") as f:
        text = generate(src_path, f.read(), const_name)
    if check:
        try:
            with open(inc_path, encoding="utf-8", newline="") as f:
                # a Windows checkout may have given the include CRLF endings
                same = f.read().replace("\r\n", "\n") == text
        except FileNotFoundError:
            same = False
        if not same:
            print("%s is out of date with %s" % (inc_path, src_path), file=sys.stderr)
            return 1
        return 0
    with open(inc_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
